export const messages: Record<Lang, Record<MessageKey, string>> = { zh, en }

export function formatMessage(template: string, params?: MessageParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

export function tMsg(lang: Lang, key: MessageKey, params?: MessageParams): string {
  return formatMessage(messages[lang][key] ?? messages.zh[key], params)
}

export type TFunction = (key: MessageKey, params?: MessageParams) => string
